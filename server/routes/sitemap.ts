router.get('/sitemap-status', async (_req, res) => {
  try {
    const supabase = getSupabaseClient();

    const [
      { count: totalPosts },
      { count: totalCats },
      { count: totalLabels },
      { count: imgPosts },
    ] = await Promise.all([
      supabase.from('posts').select('*', { count: 'exact', head: true }).eq('status', 'published'),
      supabase.from('categories').select('*', { count: 'exact', head: true }),
      supabase.from('labels').select('*', { count: 'exact', head: true }),
      supabase.from('posts').select('*', { count: 'exact', head: true }).eq('status', 'published').not('featured_image', 'is', null),
    ]);

    const postPages = Math.max(1, Math.ceil((totalPosts  || 0) / URLS_PER_SITEMAP));
    const catPages  = Math.max(1, Math.ceil(((totalCats || 0) + (totalLabels || 0)) / URLS_PER_SITEMAP));
    const imgPages  = Math.max(1, Math.ceil((imgPosts   || 0) / URLS_PER_SITEMAP));

    return res.json({
      status:      'healthy',
      generatedAt: new Date().toISOString(),
      siteUrl:     SITE_URL,
      urlsPerSitemap: URLS_PER_SITEMAP,
      stats: {
        publishedPosts:   totalPosts  || 0,
        categories:       totalCats   || 0,
        labels:           totalLabels || 0,
        postsWithImages:  imgPosts    || 0,
        estimatedTotalUrls: (totalPosts || 0) + (totalCats || 0) + (totalLabels || 0) + 11,
      },
      sitemaps: {
        index:         `${SITE_URL}/sitemap.xml`,
        authoritative: `${SITE_URL}/authoritative-sitemap.xml`,
        posts:         Array.from({ length: postPages }, (_, i) => `${SITE_URL}/posts-sitemap${i + 1}.xml`),
        categories:    Array.from({ length: catPages  }, (_, i) => `${SITE_URL}/category-sitemap${i + 1}.xml`),
        images:        Array.from({ length: imgPages  }, (_, i) => `${SITE_URL}/image-sitemap${i + 1}.xml`),
        videos:        [`${SITE_URL}/video-sitemap1.xml`],
        news:          `${SITE_URL}/news-sitemap.xml`,
      },
      cache: {
        entries:    getCacheEntries().length,
        ttlSeconds: 3600,
        details:    getCacheEntries(),
      },
      robotsTxtEntry: `Sitemap: ${SITE_URL}/sitemap.xml`,
    });
  } catch (err) {
    return res.status(500).json({ status: 'error', error: String(err) });
  }
});

